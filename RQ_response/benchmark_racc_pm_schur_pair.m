function results = benchmark_racc_pm_schur_pair( ...
        num_repeats, requested_frequency_hz, point_counts, ...
        allow_large_raw_lmi)
%BENCHMARK_RACC_PM_SCHUR_PAIR Matched global/decomposed RACC-PM timing.
%   The two methods solve the same robust SDP and differ only in whether
%   each zone-level LMI is kept global or replaced by Schur-equivalent
%   row-block LMIs.  Full-size global LMIs are skipped before allocation to
%   avoid an uncontrolled out-of-memory failure; the full-size decomposed
%   solve is retained.

    if nargin < 1 || isempty(num_repeats), num_repeats = 1; end
    if nargin < 2 || isempty(requested_frequency_hz)
        requested_frequency_hz = 1000;
    end
    if nargin < 3 || isempty(point_counts)
        point_counts = [4, 8, 16, 32, 64, 96];
    end
    if nargin < 4 || isempty(allow_large_raw_lmi)
        allow_large_raw_lmi = false;
    end
    validateattributes(num_repeats, {'numeric'}, ...
        {'scalar', 'integer', 'positive'});
    validateattributes(point_counts, {'numeric'}, ...
        {'vector', 'integer', 'positive', '<=', 96});
    validateattributes(allow_large_raw_lmi, {'logical', 'numeric'}, ...
        {'scalar'});
    allow_large_raw_lmi = logical(allow_large_raw_lmi);
    point_counts = unique(point_counts(:).', 'stable');

    response_dir = fileparts(mfilename('fullpath'));
    project_root = fileparts(response_dir);
    addpath(response_dir);
    addpath(genpath(fullfile(project_root, 'src')));
    addpath(genpath(fullfile(project_root, 'data')));
    addpath(fullfile(project_root, 'src', 'evaluations'), '-begin');
    local_verify_resolution(project_root);

    data_dir = fullfile(project_root, 'data', 'SimulateRIR', 'temperature');
    loaded_para = load(fullfile(data_dir, 'para.mat'), 'para');
    experiment_para = loaded_para.para;
    target_frequencies = experiment_para.freq_params.target_freqs(:).';
    [~, frequency_index] = min(abs( ...
        target_frequencies - requested_frequency_hz));
    frequency_hz = target_frequencies(frequency_index);
    nominal_file = get_data_filename(data_dir, 'temperature', 22.5);
    nominal = load(nominal_file);
    desired_data = load(fullfile(project_root, 'data', ...
        'ATF_desired_plane.mat'), 'ATF_desired_plane');
    HB_full = nominal.ATF_BZ.ctrl(:, :, frequency_index);
    HD_full = nominal.ATF_DZ.ctrl(:, :, frequency_index);
    desired_full = desired_data.ATF_desired_plane(:, frequency_index);
    [full_point_count, loudspeaker_count] = size(HB_full);
    if full_point_count ~= 96 || size(HD_full, 1) ~= 96 || ...
            loudspeaker_count ~= 48
        error('SchurTiming:UnexpectedGeometry', ...
            'Expected 96 points per zone and 48 loudspeakers.');
    end

    nu = 0.01;
    rho = 10;
    mu = 1;
    alpha_margin_db = 3;
    mosek_threads = 2;
    rank_fraction_threshold = 0.98;
    base_para = experiment_para.freq_params;
    base_para.target_freqs = frequency_hz;
    base_para.fre_idces = 1;
    base_para.scale = 1;
    base_para.rho = rho;
    base_para.mu = mu;
    base_para.kappa = 0.5;
    base_para.racc_pm = struct('mosek_threads', mosek_threads, ...
        'rank_fraction_threshold', rank_fraction_threshold);
    base_para.racc_pm_global = struct('max_raw_lmi_order', 2000, ...
        'allow_large_raw_lmi', allow_large_raw_lmi, ...
        'normalization_multipliers', [0.1, 1, 5, 10, 0.01]);

    full_eta_B = nu * norm(HB_full, 'fro');
    full_eta_D = nu * norm(HD_full, 'fro');
    reference_para = base_para;
    reference_para.epsilon = struct('B', full_eta_B, 'D', full_eta_D);
    reference_para.gamma = struct('B', full_eta_B^2, 'D', full_eta_D^2);
    reference = NoCT_WCRACC(reshape(HB_full, 96, 48, 1), ...
        reshape(HD_full, 96, 48, 1), reference_para, 1);
    reference_ac_db = real(calculate_AC(reference.w(:, 1), ...
        HB_full, HD_full));
    alpha = 10^((reference_ac_db - alpha_margin_db) / 10);

    output_stamp = char(datetime('now', 'Format', 'yyyyMMdd_HHmmss'));
    output_dir = fullfile(response_dir, ...
        'racc_pm_schur_timing_results', ['run_' output_stamp]);
    if ~exist(output_dir, 'dir'), mkdir(output_dir); end
    diary(fullfile(output_dir, 'matlab_diary.log'));
    diary_cleanup = onCleanup(@() diary('off'));
    local_warm_up_solver();

    formulation_names = {'global', 'subd'};
    maximum_rows = num_repeats * numel(point_counts) * ...
        numel(formulation_names);
    rows = cell(maximum_rows, 18);
    row_count = 0;
    rng(20260911, 'twister');
    for point_count = point_counts
        point_indices = unique(round(linspace(1, 96, point_count)));
        if numel(point_indices) ~= point_count
            error('SchurTiming:PointSelectionFailed', ...
                'Could not select %d unique points.', point_count);
        end
        HB = reshape(HB_full(point_indices, :), ...
            point_count, loudspeaker_count, 1);
        HD = reshape(HD_full(point_indices, :), ...
            point_count, loudspeaker_count, 1);
        desired = reshape(desired_full(point_indices), point_count, 1);
        para = base_para;
        eta_B = nu * norm(HB(:, :, 1), 'fro');
        eta_D = nu * norm(HD(:, :, 1), 'fro');
        para.epsilon = struct('B', eta_B, 'D', eta_D);
        para.gamma = struct('B', eta_B^2, 'D', eta_D^2);
        para.alpha = alpha;
        para.para_gamma = mu + rho * alpha;

        for repetition = 1:num_repeats
            order = 1:2;
            if mod(repetition, 2) == 0, order = fliplr(order); end
            for order_index = order
                formulation = formulation_names{order_index};
                raw_lmi_order = point_count * loudspeaker_count + 1;
                sub_lmi_order = loudspeaker_count + 1;
                status = "Completed";
                error_identifier = "";
                error_message = "";
                wall_seconds = NaN;
                cpu_seconds = NaN;
                control_ac_db = NaN;
                control_nsre_db = NaN;
                nominal_objective = NaN;
                selected_normalization = NaN;

                if strcmp(formulation, 'global') && ...
                        raw_lmi_order > para.racc_pm_global.max_raw_lmi_order && ...
                        ~para.racc_pm_global.allow_large_raw_lmi
                    status = "SkippedMemoryGuard";
                else
                    fprintf(['M=%d, repeat %d/%d, formulation=%s, ', ...
                        'raw order=%d, sub order=%d\n'], point_count, ...
                        repetition, num_repeats, formulation, ...
                        raw_lmi_order, sub_lmi_order);
                    cvx_clear;
                    cpu_start = cputime;
                    wall_timer = tic;
                    try
                        if strcmp(formulation, 'global')
                            solver_result = RACC_PM_GlobalMatched( ...
                                HB, HD, desired, para, 1);
                        else
                            solver_result = RACC_PM_Sub( ...
                                HB, HD, desired, para, 1);
                        end
                        wall_seconds = toc(wall_timer);
                        cpu_seconds = cputime - cpu_start;
                        status = string(solver_result.status(1));
                        selected_normalization = ...
                            solver_result.normalization_multiplier(1);
                        if local_is_solved(status)
                            w = solver_result.w(:, 1);
                            control_ac_db = real(calculate_AC( ...
                                w, HB(:, :, 1), HD(:, :, 1)));
                            error_vector = HB(:, :, 1) * w - desired;
                            control_nsre_db = 10 * log10( ...
                                norm(error_vector)^2 / norm(desired)^2);
                            nominal_objective = local_nominal_objective( ...
                                w, HB(:, :, 1), HD(:, :, 1), desired, ...
                                rho, mu + rho * alpha);
                        end
                    catch solve_error
                        wall_seconds = toc(wall_timer);
                        cpu_seconds = cputime - cpu_start;
                        status = "Failed";
                        error_identifier = string(solve_error.identifier);
                        error_message = string(solve_error.message);
                    end
                end

                row_count = row_count + 1;
                rows(row_count, :) = {point_count, repetition, ...
                    formulation, frequency_hz, loudspeaker_count, ...
                    raw_lmi_order, sub_lmi_order, point_count, ...
                    wall_seconds, cpu_seconds, char(status), ...
                    char(error_identifier), char(error_message), ...
                    control_ac_db, control_nsre_db, nominal_objective, ...
                    selected_normalization, mosek_threads};
                raw_table = cell2table(rows(1:row_count, :), ...
                    'VariableNames', {'PointsPerZone', 'Repetition', ...
                    'Formulation', 'FrequencyHz', 'Loudspeakers', ...
                    'RawLMIOrder', 'SubLMIOrder', 'SubBlocksPerZone', ...
                    'WallSeconds', 'CPUSeconds', 'Status', ...
                    'ErrorIdentifier', 'ErrorMessage', 'ControlACdB', ...
                    'ControlNSREdB', 'NominalObjective', ...
                    'NormalizationMultiplier', 'MosekThreads'});
                writetable(raw_table, fullfile(output_dir, ...
                    'racc_pm_schur_timing_raw.csv'));
                fprintf('Status=%s, wall=%.3f s, CPU=%.3f s\n', ...
                    status, wall_seconds, cpu_seconds);
            end
        end
    end

    completed = raw_table(ismember(string(raw_table.Status), ...
        ["Solved", "Inaccurate/Solved"]), :);
    if isempty(completed)
        summary = table();
    else
        [groups, point_group, formulation_group] = findgroups( ...
            completed.PointsPerZone, completed.Formulation);
        summary = table(point_group, formulation_group, ...
            splitapply(@numel, completed.WallSeconds, groups), ...
            splitapply(@mean, completed.WallSeconds, groups), ...
            splitapply(@std, completed.WallSeconds, groups), ...
            splitapply(@mean, completed.CPUSeconds, groups), ...
            splitapply(@std, completed.CPUSeconds, groups), ...
            splitapply(@mean, completed.ControlACdB, groups), ...
            splitapply(@mean, completed.ControlNSREdB, groups), ...
            'VariableNames', {'PointsPerZone', 'Formulation', ...
            'SuccessfulRepeats', 'MeanWallSeconds', 'StdWallSeconds', ...
            'MeanCPUSeconds', 'StdCPUSeconds', 'MeanControlACdB', ...
            'MeanControlNSREdB'});
    end
    writetable(summary, fullfile(output_dir, ...
        'racc_pm_schur_timing_summary.csv'));
    scaling_rows = cell(numel(point_counts), 14);
    for point_index = 1:numel(point_counts)
        point_count = point_counts(point_index);
        global_all = raw_table(raw_table.PointsPerZone == point_count & ...
            strcmp(raw_table.Formulation, 'global'), :);
        subd_all = raw_table(raw_table.PointsPerZone == point_count & ...
            strcmp(raw_table.Formulation, 'subd'), :);
        global_done = global_all(ismember(string(global_all.Status), ...
            ["Solved", "Inaccurate/Solved"]), :);
        subd_done = subd_all(ismember(string(subd_all.Status), ...
            ["Solved", "Inaccurate/Solved"]), :);
        global_mean = NaN;
        subd_mean = NaN;
        speedup = NaN;
        global_cpu_mean = NaN;
        subd_cpu_mean = NaN;
        cpu_speedup = NaN;
        if ~isempty(global_done), global_mean = mean(global_done.WallSeconds); end
        if ~isempty(subd_done), subd_mean = mean(subd_done.WallSeconds); end
        if ~isempty(global_done)
            global_cpu_mean = mean(global_done.CPUSeconds);
        end
        if ~isempty(subd_done)
            subd_cpu_mean = mean(subd_done.CPUSeconds);
        end
        if isfinite(global_mean) && isfinite(subd_mean)
            speedup = global_mean / subd_mean;
        end
        if isfinite(global_cpu_mean) && isfinite(subd_cpu_mean)
            cpu_speedup = global_cpu_mean / subd_cpu_mean;
        end
        scaling_rows(point_index, :) = {point_count, ...
            point_count * loudspeaker_count + 1, loudspeaker_count + 1, ...
            point_count, local_join_status(global_all.Status), ...
            height(global_done), global_mean, global_cpu_mean, ...
            local_join_status(subd_all.Status), height(subd_done), ...
            subd_mean, subd_cpu_mean, speedup, cpu_speedup};
    end
    scaling_summary = cell2table(scaling_rows, 'VariableNames', ...
        {'PointsPerZone', 'RawLMIOrder', 'SubLMIOrder', ...
        'SubBlocksPerZone', 'GlobalStatus', 'SuccessfulGlobalRepeats', ...
        'MeanGlobalWallSeconds', 'MeanGlobalCPUSeconds', 'SubdStatus', ...
        'SuccessfulSubdRepeats', 'MeanSubdWallSeconds', ...
        'MeanSubdCPUSeconds', 'WallSpeedup', 'CPUSpeedup'});
    writetable(scaling_summary, fullfile(output_dir, ...
        'racc_pm_schur_scaling_summary.csv'));
    paired_rows = cell(0, 7);
    for point_count = point_counts
        global_row = summary(summary.PointsPerZone == point_count & ...
            strcmp(summary.Formulation, 'global'), :);
        subd_row = summary(summary.PointsPerZone == point_count & ...
            strcmp(summary.Formulation, 'subd'), :);
        if height(global_row) == 1 && height(subd_row) == 1
            paired_rows(end + 1, :) = {point_count, ...
                global_row.MeanWallSeconds, subd_row.MeanWallSeconds, ...
                global_row.MeanWallSeconds / subd_row.MeanWallSeconds, ...
                abs(global_row.MeanControlACdB - subd_row.MeanControlACdB), ...
                abs(global_row.MeanControlNSREdB - ...
                    subd_row.MeanControlNSREdB), ...
                abs(mean(completed.NominalObjective( ...
                    completed.PointsPerZone == point_count & ...
                    strcmp(completed.Formulation, 'global'))) - ...
                    mean(completed.NominalObjective( ...
                    completed.PointsPerZone == point_count & ...
                    strcmp(completed.Formulation, 'subd'))))}; %#ok<AGROW>
        end
    end
    paired_summary = cell2table(paired_rows, 'VariableNames', ...
        {'PointsPerZone', 'MeanGlobalWallSeconds', ...
        'MeanSubdWallSeconds', 'WallSpeedup', 'AbsControlACDifferenceDb', ...
        'AbsControlNSREDifferenceDb', 'AbsNominalObjectiveDifference'});
    writetable(paired_summary, fullfile(output_dir, ...
        'racc_pm_schur_paired_summary.csv'));
    configuration = struct('created_at', char(datetime('now')), ...
        'frequency_hz', frequency_hz, 'point_counts', point_counts, ...
        'loudspeaker_count', loudspeaker_count, 'nu', nu, 'rho', rho, ...
        'mu', mu, 'alpha_margin_db', alpha_margin_db, 'alpha', alpha, ...
        'reference_ac_db', reference_ac_db, ...
        'mosek_threads', mosek_threads, ...
        'allow_large_raw_lmi', allow_large_raw_lmi, ...
        'global_solver', which('RACC_PM_GlobalMatched'), ...
        'subd_solver', which('RACC_PM_Sub'), ...
        'evaluator', which('evaluate_performance'), ...
        'timed_scope', 'CVX model construction, solve, and recovery');
    results = struct('configuration', configuration, ...
        'raw', raw_table, 'summary', summary, ...
        'scaling_summary', scaling_summary, ...
        'paired_summary', paired_summary, 'output_dir', output_dir);
    save(fullfile(output_dir, 'racc_pm_schur_timing_results.mat'), ...
        'results', '-v7.3');
    marker = fopen(fullfile(output_dir, 'RUN_COMPLETED.txt'), 'w');
    if marker >= 0
        fprintf(marker, 'Completed: %s\n', char(datetime('now')));
        fclose(marker);
    end
    disp(summary);
end

function status_text = local_join_status(status_values)
    status_values = unique(string(status_values), 'stable');
    if isempty(status_values)
        status_text = 'NotRun';
    else
        status_text = char(strjoin(status_values, '|'));
    end
end

function local_verify_resolution(project_root)
    expected_evaluator = fullfile(project_root, 'src', 'evaluations', ...
        'evaluate_performance.m');
    if ~strcmpi(which('evaluate_performance'), expected_evaluator)
        error('SchurTiming:WrongEvaluator', ...
            'Unexpected evaluate_performance resolution: %s', ...
            which('evaluate_performance'));
    end
    expected_subd = fullfile(project_root, 'src', 'algorithm', ...
        'RACC_PM_Sub.m');
    if ~strcmpi(which('RACC_PM_Sub'), expected_subd)
        error('SchurTiming:WrongSubdSolver', ...
            'Unexpected RACC_PM_Sub resolution: %s', which('RACC_PM_Sub'));
    end
end

function local_warm_up_solver()
    cvx_clear;
    cvx_begin quiet
        cvx_solver mosek
        variable x
        minimize(square(x - 1))
    cvx_end
    cvx_clear;
end

function solved = local_is_solved(status)
    solved = strcmp(status, 'Solved') || ...
        strcmp(status, 'Inaccurate/Solved');
end

function value = local_nominal_objective( ...
        w, HB, HD, desired, rho, gamma)
    bright_pressure = HB * w;
    dark_pressure = HD * w;
    error_vector = desired - bright_pressure;
    value = real(error_vector' * error_vector ...
        - rho * (bright_pressure' * bright_pressure) ...
        + gamma * (dark_pressure' * dark_pressure));
end
