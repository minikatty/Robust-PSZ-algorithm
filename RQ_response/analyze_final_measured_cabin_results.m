function outputs = analyze_final_measured_cabin_results(result_file)
%ANALYZE_FINAL_MEASURED_CABIN_RESULTS Audit and summarize the final cabin run.
%   This is descriptive condition-level analysis. It does not treat the 59
%   held-out ATFs as independent subjects and reports no population p-values.

if nargin < 1 || isempty(result_file)
    response_dir = fileparts(mfilename('fullpath'));
    result_file = fullfile(response_dir, ...
        'final_measured_cabin_results', 'run_20260829_152136', ...
        'final_measured_cabin_results.mat');
end
loaded = load(result_file, 'experiment');
experiment = loaded.experiment;
output_dir = fullfile(experiment.output_dir, 'analysis');
if ~exist(output_dir, 'dir')
    mkdir(output_dir);
end

local_audit_experiment(experiment);
band_summary = experiment.band_summary;
winner_table = local_winners(band_summary);
writetable(winner_table, fullfile(output_dir, ...
    'metric_winners_by_band.csv'));

comparison_table = local_key_comparisons(band_summary);
writetable(comparison_table, fullfile(output_dir, ...
    'key_pairwise_band_deltas.csv'));

solver_audit = local_solver_audit(experiment);
writetable(solver_audit, fullfile(output_dir, 'solver_audit.csv'));
racc_constraint_audit = local_racc_constraint_audit(experiment);
writetable(racc_constraint_audit, fullfile(output_dir, ...
    'racc_pm_extracted_filter_constraint_audit.csv'));

summary_file = fullfile(output_dir, 'analysis_summary.txt');
local_write_summary(summary_file, experiment, band_summary, ...
    comparison_table, solver_audit, racc_constraint_audit);

analysis = struct('winner_table', winner_table, ...
    'comparison_table', comparison_table, ...
    'solver_audit', solver_audit, ...
    'racc_constraint_audit', racc_constraint_audit, ...
    'summary_file', summary_file, ...
    'created_at', datetime('now'));
analysis_file = fullfile(output_dir, 'analysis_results.mat');
save(analysis_file, 'analysis', '-v7');

fprintf('Final measured-cabin analysis: %s\n', summary_file);
outputs = struct('output_dir', output_dir, ...
    'summary_file', summary_file, 'analysis_file', analysis_file, ...
    'winner_table', winner_table, ...
    'comparison_table', comparison_table, ...
    'solver_audit', solver_audit, ...
    'racc_constraint_audit', racc_constraint_audit);
end

function local_audit_experiment(experiment)
assert(numel(experiment.algorithm_fields) == 11, ...
    'Expected the complete 11-algorithm set.');
assert(numel(experiment.validation_indices) == 59, ...
    'Expected 59 held-out operating conditions.');
assert(numel(experiment.frequencies) == 50, ...
    'Expected the measured 50-frequency grid.');
metrics = {'AC', 'NSRE', 'AE', 'BZ_SPL_Variance', ...
    'BZ_SPL_Std', 'BZ_SPL_Range'};
for algorithm = experiment.algorithm_fields(:).'
    name = char(algorithm);
    for metric_no = 1:numel(metrics)
        values = experiment.val_results.(name).(metrics{metric_no});
        assert(isequal(size(values), [59, 50]), ...
            'Unexpected metric dimensions for %s/%s.', ...
            name, metrics{metric_no});
        assert(all(isfinite(values(:))), ...
            'Nonfinite metric values for %s/%s.', name, metrics{metric_no});
    end
end
for algorithm = ["Full_WCRACC", "POTDC_RACC", "RACC_PM_Subpro"]
    statuses = string(experiment.algorithm_details.(char(algorithm)).status);
    solved = statuses == "Solved" | statuses == "Inaccurate/Solved";
    assert(all(solved), '%s has an unsolved frequency.', algorithm);
end
end

function winners = local_winners(summary)
metric_names = ["AC_Mean_dB", "AC_WorstCondition_dB", ...
    "NSRE_Mean_dB", "NSRE_WorstCondition_dB", "AE_Mean_dB", ...
    "BZ_SPL_Variance_Mean_dB2", "BZ_SPL_Std_Mean_dB", ...
    "BZ_SPL_Range_Mean_dB", "BZ_SPL_Range_WorstCondition_dB"];
directions = ["max", "max", "min", "min", "min", ...
    "min", "min", "min", "min"];
groups = {"All", "RobustEnergy"};
robust_energy = ["ACC_Reg", "wcRACC", "NoCT_WCRACC", ...
    "Full_WCRACC", "POTDC_RACC", "RACC_PM_Subpro"];
rows = cell(numel(unique(summary.Band, 'stable')) * ...
    numel(metric_names) * numel(groups), 8);
row = 0;
bands = unique(summary.Band, 'stable');
for band_no = 1:numel(bands)
    band_rows = summary(summary.Band == bands(band_no), :);
    for group_no = 1:numel(groups)
        if groups{group_no} == "RobustEnergy"
            candidates = band_rows(ismember( ...
                band_rows.AlgorithmField, robust_energy), :);
        else
            candidates = band_rows;
        end
        for metric_no = 1:numel(metric_names)
            values = candidates.(metric_names(metric_no));
            if directions(metric_no) == "max"
                [best_value, best_index] = max(values);
            else
                [best_value, best_index] = min(values);
            end
            row = row + 1;
            rows(row, :) = {bands(band_no), groups{group_no}, ...
                metric_names(metric_no), directions(metric_no), ...
                candidates.Algorithm(best_index), ...
                candidates.AlgorithmField(best_index), best_value, ...
                height(candidates)};
        end
    end
end
winners = cell2table(rows, 'VariableNames', {'Band', 'CandidateGroup', ...
    'Metric', 'Direction', 'Winner', 'WinnerField', 'WinnerValue', ...
    'CandidateCount'});
end

function comparisons = local_key_comparisons(summary)
pairs = [ ...
    "RACC_PM_Subpro", "ACC_Reg"; ...
    "RACC_PM_Subpro", "Full_WCRACC"; ...
    "RACC_PM_Subpro", "NoCT_WCRACC"; ...
    "RACC_PM_Subpro", "POTDC_RACC"; ...
    "M_ACC", "ACC"; ...
    "M_ACC", "ACC_Reg"; ...
    "M_ACC", "PM"; ...
    "M_ACC", "RPM"; ...
    "ACC", "ACC_Reg"];
metrics = ["AC_Mean_dB", "AC_WorstCondition_dB", ...
    "NSRE_Mean_dB", "AE_Mean_dB", ...
    "BZ_SPL_Variance_Mean_dB2", "BZ_SPL_Std_Mean_dB", ...
    "BZ_SPL_Range_Mean_dB", "BZ_SPL_Range_WorstCondition_dB"];
bands = unique(summary.Band, 'stable');
rows = cell(numel(bands) * size(pairs, 1) * numel(metrics), 11);
row = 0;
for band_no = 1:numel(bands)
    for pair_no = 1:size(pairs, 1)
        candidate = summary(summary.Band == bands(band_no) & ...
            summary.AlgorithmField == pairs(pair_no, 1), :);
        reference = summary(summary.Band == bands(band_no) & ...
            summary.AlgorithmField == pairs(pair_no, 2), :);
        assert(height(candidate) == 1 && height(reference) == 1);
        for metric_no = 1:numel(metrics)
            candidate_value = candidate.(metrics(metric_no));
            reference_value = reference.(metrics(metric_no));
            row = row + 1;
            rows(row, :) = {bands(band_no), candidate.Algorithm, ...
                candidate.AlgorithmField, reference.Algorithm, ...
                reference.AlgorithmField, metrics(metric_no), ...
                candidate_value, reference_value, ...
                candidate_value - reference_value, ...
                candidate_value / max(abs(reference_value), realmin), ...
                100 * (candidate_value - reference_value) / ...
                max(abs(reference_value), realmin)};
        end
    end
end
comparisons = cell2table(rows, 'VariableNames', {'Band', ...
    'Candidate', 'CandidateField', 'Reference', 'ReferenceField', ...
    'Metric', 'CandidateValue', 'ReferenceValue', ...
    'CandidateMinusReference', 'SignedRatioToAbsReference', ...
    'SignedPercentOfAbsReference'});
end

function audit = local_solver_audit(experiment)
full_detail = experiment.algorithm_details.Full_WCRACC;
potdc_detail = experiment.algorithm_details.POTDC_RACC;
racc_detail = experiment.algorithm_details.RACC_PM_Subpro;
rows = cell(3, 10);
rows(1, :) = {"Full-WCRACC", 50, ...
    sum(local_solved(full_detail.status)), ...
    min(full_detail.rank_fraction), median(full_detail.rank_fraction), ...
    max(full_detail.rank_fraction), NaN, NaN, ...
    strjoin(string(unique(full_detail.normalization_multiplier)), ','), ...
    "Recovered feasible filters; relaxation is not reported as AC"};
rows(2, :) = {"POTDC-RACC", 50, ...
    sum(local_solved(potdc_detail.status)), ...
    min(potdc_detail.rank_fraction), median(potdc_detail.rank_fraction), ...
    max(potdc_detail.rank_fraction), ...
    min(potdc_detail.iterations), max(potdc_detail.iterations), ...
    "not applicable", "All frequency-level statuses solved"};
rows(3, :) = {"RACC-PM", 50, ...
    sum(local_solved(racc_detail.status)), NaN, NaN, NaN, NaN, NaN, ...
    strjoin(string(unique(racc_detail.normalization_multiplier)), ','), ...
    "Maintained no-suffix RACC_PM_Sub; MOSEK decomposed LMI"};
audit = cell2table(rows, 'VariableNames', {'Algorithm', ...
    'FrequencyCount', 'SolvedCount', 'MinimumRankFraction', ...
    'MedianRankFraction', 'MaximumRankFraction', ...
    'MinimumIterations', 'MaximumIterations', ...
    'NormalizationMultipliers', 'Note'});
end

function audit = local_racc_constraint_audit(experiment)
reference = load(experiment.reference_file, 'ATF_BZ', 'ATF_DZ');
filters = experiment.all_filters.RACC_PM_Subpro;
frequency_count = numel(experiment.frequencies);
AchievedAlpha = nan(frequency_count, 1);
for frequency_no = 1:frequency_count
    [~, AchievedAlpha(frequency_no)] = full_racc_worst_case_contrast( ...
        filters(:, frequency_no), reference.ATF_BZ(:, :, frequency_no), ...
        reference.ATF_DZ(:, :, frequency_no), ...
        experiment.signature.eta_B(frequency_no), ...
        experiment.signature.eta_D(frequency_no), 0, 0);
end
FrequencyIndex = (1:frequency_count).';
Frequency_Hz = experiment.frequencies(:);
TargetAlpha = experiment.signature.alpha_AC(:);
TargetAC_dB = 10 * log10(max(TargetAlpha, realmin));
AchievedAC_dB = 10 * log10(max(AchievedAlpha, realmin));
ConstraintGap_dB = AchievedAC_dB - TargetAC_dB;
FeasibleWithinTolerance = ConstraintGap_dB >= -1e-6;
audit = table(FrequencyIndex, Frequency_Hz, TargetAlpha, ...
    TargetAC_dB, AchievedAlpha, AchievedAC_dB, ConstraintGap_dB, ...
    FeasibleWithinTolerance);
assert(all(FeasibleWithinTolerance), ...
    'An extracted RACC-PM filter violates the full-ball AC constraint.');
end

function solved = local_solved(statuses)
statuses = string(statuses);
solved = statuses == "Solved" | statuses == "Inaccurate/Solved";
end

function local_write_summary(file, experiment, summary, comparisons, audit, ...
        racc_constraint_audit)
file_id = fopen(file, 'w');
if file_id < 0
    error('FinalCabinAnalysis:SummaryOpenFailed', ...
        'Could not create %s.', file);
end
cleanup = onCleanup(@() fclose(file_id));
fprintf(file_id, 'Final measured-cabin descriptive analysis\n');
fprintf(file_id, '=========================================\n\n');
fprintf(file_id, 'Result: %s\n', fullfile(experiment.output_dir, ...
    'final_measured_cabin_results.mat'));
fprintf(file_id, 'Reference: ATF_%d; held-out conditions: %d\n', ...
    experiment.config.reference_index, numel(experiment.validation_indices));
fprintf(file_id, 'Algorithms: %d; frequencies: %d (%g--%g Hz)\n', ...
    numel(experiment.algorithm_fields), numel(experiment.frequencies), ...
    experiment.frequencies(1), experiment.frequencies(end));
fprintf(file_id, ['Statistics are condition-level descriptive summaries; ', ...
    'the 59 ATFs are not treated as independent subjects.\n\n']);

full = summary(summary.Band == "Full_100_4000", :);
racc = full(full.AlgorithmField == "RACC_PM_Subpro", :);
acc_reg = full(full.AlgorithmField == "ACC_Reg", :);
potdc = full(full.AlgorithmField == "POTDC_RACC", :);
macc = full(full.AlgorithmField == "M_ACC", :);
acc = full(full.AlgorithmField == "ACC", :);
pm = full(full.AlgorithmField == "PM", :);
fprintf(file_id, '100--4000 Hz principal results\n');
fprintf(file_id, '-------------------------------\n');
fprintf(file_id, ['RACC-PM: AC mean/worst %.3f/%.3f dB, NSRE %.3f dB, ', ...
    'AE %.3f dB, BZ SPL std/range %.3f/%.3f dB.\n'], ...
    racc.AC_Mean_dB, racc.AC_WorstCondition_dB, racc.NSRE_Mean_dB, ...
    racc.AE_Mean_dB, racc.BZ_SPL_Std_Mean_dB, ...
    racc.BZ_SPL_Range_Mean_dB);
fprintf(file_id, ['Versus ACC-Reg, RACC-PM changes mean/worst AC by ', ...
    '%+.3f/%+.3f dB and mean NSRE by %+.3f dB.\n'], ...
    racc.AC_Mean_dB - acc_reg.AC_Mean_dB, ...
    racc.AC_WorstCondition_dB - acc_reg.AC_WorstCondition_dB, ...
    racc.NSRE_Mean_dB - acc_reg.NSRE_Mean_dB);
fprintf(file_id, ['Versus POTDC-RACC, RACC-PM changes mean/worst AC by ', ...
    '%+.3f/%+.3f dB and mean NSRE by %+.3f dB.\n'], ...
    racc.AC_Mean_dB - potdc.AC_Mean_dB, ...
    racc.AC_WorstCondition_dB - potdc.AC_WorstCondition_dB, ...
    racc.NSRE_Mean_dB - potdc.NSRE_Mean_dB);
fprintf(file_id, ['These differences are small and support robustness ', ...
    'parity, not a large cabin advantage.\n\n']);

fprintf(file_id, ['M-ACC: AC mean/worst %.3f/%.3f dB, BZ SPL ', ...
    'variance/std/range %.3f/%.3f/%.3f.\n'], ...
    macc.AC_Mean_dB, macc.AC_WorstCondition_dB, ...
    macc.BZ_SPL_Variance_Mean_dB2, macc.BZ_SPL_Std_Mean_dB, ...
    macc.BZ_SPL_Range_Mean_dB);
fprintf(file_id, ['Relative to ACC, M-ACC changes mean AC by %+.3f dB ', ...
    'and reduces mean variance/std/range by %.2f/%.2f/%.2f%%.\n'], ...
    macc.AC_Mean_dB - acc.AC_Mean_dB, ...
    100 * (acc.BZ_SPL_Variance_Mean_dB2 - ...
    macc.BZ_SPL_Variance_Mean_dB2) / acc.BZ_SPL_Variance_Mean_dB2, ...
    100 * (acc.BZ_SPL_Std_Mean_dB - macc.BZ_SPL_Std_Mean_dB) / ...
    acc.BZ_SPL_Std_Mean_dB, ...
    100 * (acc.BZ_SPL_Range_Mean_dB - macc.BZ_SPL_Range_Mean_dB) / ...
    acc.BZ_SPL_Range_Mean_dB);
fprintf(file_id, ['M-ACC has the lowest mean BZ SPL variance/std/range ', ...
    'of all methods; PM still gives substantially lower NSRE ', ...
    '(%.3f versus %.3f dB).\n\n'], pm.NSRE_Mean_dB, macc.NSRE_Mean_dB);

paper = summary(summary.Band == "Paper_100_2000", :);
paper_racc = paper(paper.AlgorithmField == "RACC_PM_Subpro", :);
paper_macc = paper(paper.AlgorithmField == "M_ACC", :);
fprintf(file_id, '100--2000 Hz paper-aligned check\n');
fprintf(file_id, '--------------------------------\n');
fprintf(file_id, ['RACC-PM mean/worst AC %.3f/%.3f dB; ', ...
    'M-ACC mean range %.3f dB.\n\n'], ...
    paper_racc.AC_Mean_dB, paper_racc.AC_WorstCondition_dB, ...
    paper_macc.BZ_SPL_Range_Mean_dB);

fprintf(file_id, 'Solver and protocol audit\n');
fprintf(file_id, '-------------------------\n');
for row = 1:height(audit)
    fprintf(file_id, '%s: %d/%d solved; %s.\n', ...
        audit.Algorithm(row), audit.SolvedCount(row), ...
        audit.FrequencyCount(row), audit.Note(row));
end
fprintf(file_id, ['RACC-PM alpha is the zero-margin full-ATF-ball ', ...
    'contrast attained by the nominal NoCT control filter: ', ...
    '%.3f--%.3f dB.\n'], ...
    min(10 * log10(experiment.signature.alpha_AC)), ...
    max(10 * log10(experiment.signature.alpha_AC)));
fprintf(file_id, 'M-ACC selected alpha: %.6g.\n', ...
    experiment.selected_macc_alpha);
fprintf(file_id, ['RACC-PM extracted-filter full-ball constraint gap ', ...
    'min/median/max: %.3f/%.3f/%.3f dB; feasible frequencies: %d/%d.\n'], ...
    min(racc_constraint_audit.ConstraintGap_dB), ...
    median(racc_constraint_audit.ConstraintGap_dB), ...
    max(racc_constraint_audit.ConstraintGap_dB), ...
    sum(racc_constraint_audit.FeasibleWithinTolerance), ...
    height(racc_constraint_audit));
reference = experiment.reference_diagnostic( ...
    experiment.reference_diagnostic.SelectedReference, :);
fprintf(file_id, ['ATF-2 retrospective centrality rank: %d/60 ', ...
    '(%.2f percentile; lower is more central).\n\n'], ...
    reference.CentralityRank_LowerIsMoreCentral, ...
    reference.CentralityPercentile_LowerIsMoreCentral);

fprintf(file_id, 'Interpretation boundary\n');
fprintf(file_id, '-----------------------\n');
fprintf(file_id, ['The 59 held-out ATFs are participant/head-orientation ', ...
    'operating conditions from three participants with unavailable ', ...
    'record-level labels. Do not report n=59 subject-level significance.\n']);
fprintf(file_id, ['The measured perturbations are far outside nu=0.01; ', ...
    'this is an out-of-set deployment stress test, not an empirical ', ...
    'coverage demonstration of the deterministic uncertainty ball.\n']);
fprintf(file_id, ['Planarity is omitted because verified cabin microphone ', ...
    'coordinates and a target wave direction are unavailable.\n']);
fprintf(file_id, ['Development runtimes in this resumed run are diagnostic ', ...
    'only; use the planned clean-machine repeated timing for the paper.\n']);

% Retain the input to make the summary generation traceable in the MAT.
if isempty(comparisons)
    error('FinalCabinAnalysis:EmptyComparisons', ...
        'The key comparison table is unexpectedly empty.');
end
end
